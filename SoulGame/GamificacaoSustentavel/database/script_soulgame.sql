        PRIMARY KEY (ID_REGISTRO),

    CONSTRAINT CK_REG_STATUS
        CHECK (
            STATUS_VALIDACAO IN (
                'PENDENTE',
                'VALIDADO',
                'REJEITADO'
            )
        ),

    CONSTRAINT CK_REG_PONTOS
        CHECK (
            PONTOS_OBTIDOS >= 0
        ),

    CONSTRAINT FK_REG_ACAO_SUST
